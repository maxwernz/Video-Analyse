"""The Category template: a reusable starting collection copied into an Analysis.

CONTEXT.md: a Category template is "a reusable starting collection of
Categories that is copied into an Analysis and may then be customized without
changing the template. The initial template is designed for handball
analysis." Two things fall out of that sentence and are enforced here:

- The template is its own ordered, named, color-coded collection —
  `CategoryTemplate` — independent of any `Analysis`. It validates exactly the
  way `Analysis` validates its own Categories (trimmed, non-empty, unique
  names; stable identities across rename and reorder), because it is the same
  kind of data; it is a separate type because it owns no Clips and is never
  itself a document.
- Copying it into an Analysis (`apply_category_template`) must be a *copy*: a
  Category an Analysis holds gets its own fresh UUID, generated by
  `Analysis.add_category` because no identity is ever passed across this
  boundary. That is what keeps a later template edit from ever reaching into
  an Analysis that already copied it — the isolation #18 requires, and it
  falls out of the existing primitive rather than needing one of its own.

`new_analysis_document` stays the single construction path #68 established:
`ApplicationWorkflow.new_analysis` and `main.build_workspace_context` both
call it with no arguments, so an analyst's very first Analysis and every
"File > New" afterwards start from the same template. Reading the
installation-local template that Category-template management (#18) lets an
analyst customize is therefore a default of *this* function rather than
something each caller must remember to ask for — done through a deferred
import so that `analysis/`, which the rest of this package keeps free of Qt,
stays importable without it whenever a caller passes its own template
explicitly (every existing test does).
"""

from __future__ import annotations

from collections.abc import Iterable, Sequence
from dataclasses import dataclass, replace
from uuid import UUID, uuid4

from .document import AnalysisDocument
from .errors import InvalidAnalysisDataError, UnknownEntityError
from .model import Analysis, normalize_category_name

#: The installation-local starting Categories copied into a new Analysis,
#: designed for handball analysis, and what "restore the built-in template"
#: returns to.
DEFAULT_CATEGORY_TEMPLATE: tuple[tuple[str, str], ...] = (
    ("Abwehr", "#3B82F6"),
    ("Angriff", "#EF4444"),
    ("Tor", "#22C55E"),
)


@dataclass(frozen=True, slots=True)
class CategoryTemplateEntry:
    """One Category the template offers.

    The identity exists only inside the template — it lets template
    management rename or recolor one entry unambiguously — and is never the
    identity a copy gets inside an Analysis; see the module docstring.
    """

    id: UUID
    name: str
    color: str


class CategoryTemplate:
    """An ordered, named, color-coded collection, independent of any Analysis.

    Every mutating method here raises `InvalidAnalysisDataError` or
    `UnknownEntityError` exactly where `Analysis`'s own Category methods do,
    for the same reasons: this is the same validation, on data that happens
    to live outside a document.
    """

    def __init__(self, entries: Iterable[CategoryTemplateEntry] = ()) -> None:
        self._entries: list[CategoryTemplateEntry] = list(entries)

    @property
    def entries(self) -> tuple[CategoryTemplateEntry, ...]:
        return tuple(self._entries)

    @classmethod
    def default(cls) -> CategoryTemplate:
        """The built-in handball template."""

        template = cls()
        for name, color in DEFAULT_CATEGORY_TEMPLATE:
            template.add(name, color)
        return template

    def entry(self, entry_id: UUID) -> CategoryTemplateEntry:
        found = next(
            (entry for entry in self._entries if entry.id == entry_id), None
        )
        if found is None:
            raise UnknownEntityError("Category template has no such Category")
        return found

    def add(self, name: str, color: str) -> CategoryTemplateEntry:
        normalized_name = normalize_category_name(name)
        if not isinstance(color, str) or not color.strip():
            raise InvalidAnalysisDataError("Category color must not be empty")
        if any(
            normalize_category_name(entry.name) == normalized_name
            for entry in self._entries
        ):
            raise InvalidAnalysisDataError(
                f"Category names must be unique: {name!r}"
            )
        entry = CategoryTemplateEntry(uuid4(), name.strip(), color)
        self._entries.append(entry)
        return entry

    def rename(self, entry_id: UUID, name: str) -> CategoryTemplateEntry:
        entry = self.entry(entry_id)
        normalized_name = normalize_category_name(name)
        if any(
            other.id != entry_id
            and normalize_category_name(other.name) == normalized_name
            for other in self._entries
        ):
            raise InvalidAnalysisDataError(
                f"Category names must be unique: {name!r}"
            )
        updated = replace(entry, name=name.strip())
        self._entries[self._entries.index(entry)] = updated
        return updated

    def recolor(self, entry_id: UUID, color: str) -> CategoryTemplateEntry:
        entry = self.entry(entry_id)
        if not isinstance(color, str) or not color.strip():
            raise InvalidAnalysisDataError("Category color must not be empty")
        updated = replace(entry, color=color)
        self._entries[self._entries.index(entry)] = updated
        return updated

    def reorder(self, entry_ids: Sequence[UUID]) -> None:
        ordered_ids = list(entry_ids)
        known_ids = {entry.id for entry in self._entries}
        if len(ordered_ids) != len(known_ids) or set(ordered_ids) != known_ids:
            raise InvalidAnalysisDataError(
                "Category order must name every template Category exactly once"
            )
        by_id = {entry.id: entry for entry in self._entries}
        self._entries = [by_id[identity] for identity in ordered_ids]

    def remove(self, entry_id: UUID) -> None:
        self._entries.remove(self.entry(entry_id))


def apply_category_template(
    analysis: Analysis,
    template: Iterable[tuple[str, str]] | CategoryTemplate = DEFAULT_CATEGORY_TEMPLATE,
) -> None:
    """Copy a Category template into an Analysis, skipping names it already has.

    Each copy is a new `Category` with a fresh UUID: see the module docstring
    for why that is what makes template edits unable to reach a document that
    already holds a copy.
    """

    pairs: Iterable[tuple[str, str]] = (
        tuple((entry.name, entry.color) for entry in template.entries)
        if isinstance(template, CategoryTemplate)
        else template
    )
    for name, color in pairs:
        if analysis.category_named(name) is None:
            analysis.add_category(name, color)


def new_analysis_document(
    title: str = "",
    *,
    template: Iterable[tuple[str, str]] | CategoryTemplate | None = None,
) -> AnalysisDocument:
    """Create a clean, empty Analysis document seeded with the Category template.

    With no `template` given, this reads the installation-local durable
    template (`category_template_store.CategoryTemplateStore`), falling back
    to the built-in handball set exactly the way that store already does for
    a missing or corrupt file — so this function can never fail to produce a
    usable starting Analysis. Passing `template` explicitly (every existing
    caller in this test suite does) bypasses the store entirely, which is
    what keeps every test that does not care about the durable template free
    of it.
    """

    analysis = Analysis(title)
    apply_category_template(
        analysis, template if template is not None else _installed_template()
    )
    return AnalysisDocument(analysis)


def _installed_template() -> CategoryTemplate:
    """The durable, installation-local template, tolerant of every failure.

    Imported lazily so that `analysis/` — Qt-free everywhere else in this
    package — only reaches for `QStandardPaths` on the one call path that
    actually needs the installed template, not on every import of this
    module.
    """

    from category_template_store import CategoryTemplateStore

    try:
        return CategoryTemplateStore().load()
    except Exception:
        return CategoryTemplate.default()


